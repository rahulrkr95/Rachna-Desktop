// ── Project registry ─────────────────────────────────────────────────────
//
// Lightweight record of every project root the app has ever opened, so
// "recent projects" style UI can be powered without touching any
// individual project's own `project.db` (which may not even exist yet if
// that project has never been indexed).

/// A single project-registry entry.
#[derive(Debug, Clone, Serialize)]
pub struct ProjectRegistryEntry {
    pub project_root: String,
    pub display_name: String,
    pub first_opened_at: String,
    pub last_opened_at: String,
}

fn row_to_project_registry_entry(row: &rusqlite::Row) -> SqlResult<ProjectRegistryEntry> {
    Ok(ProjectRegistryEntry {
        project_root: row.get(0)?,
        display_name: row.get(1)?,
        first_opened_at: row.get(2)?,
        last_opened_at: row.get(3)?,
    })
}

/// Registers `project_root` as opened (inserting it on first open, or just
/// bumping `last_opened_at` if it's already known). `display_name` is
/// updated on every call so a renamed folder's registry entry stays fresh.
pub fn touch_project_registry(
    app_data_dir: &PathBuf,
    project_root: &str,
    display_name: &str,
) -> SqlResult<()> {
    let conn = open_app_db(app_data_dir)?;
    let now = chrono_now();
    conn.execute(
        "INSERT INTO project_registry (project_root, display_name, first_opened_at, last_opened_at)
         VALUES (?1, ?2, ?3, ?3)
         ON CONFLICT(project_root) DO UPDATE SET
             display_name = excluded.display_name,
             last_opened_at = excluded.last_opened_at",
        params![project_root, display_name, now],
    )?;
    Ok(())
}

/// Lists every registered project, most-recently-opened first.
pub fn list_project_registry(app_data_dir: &PathBuf) -> SqlResult<Vec<ProjectRegistryEntry>> {
    let conn = open_app_db(app_data_dir)?;
    let mut stmt = conn.prepare(
        "SELECT project_root, display_name, first_opened_at, last_opened_at
         FROM project_registry
         ORDER BY last_opened_at DESC",
    )?;
    let rows = stmt
        .query_map([], row_to_project_registry_entry)?
        .filter_map(|r| r.ok())
        .collect();
    Ok(rows)
}

/// Removes a project from the registry (e.g. "remove from recent list").
