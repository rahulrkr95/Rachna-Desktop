        let dir = tempfile::tempdir().unwrap();
        let app_data_dir = dir.path().to_path_buf();
        write_legacy_combined_app_db(&app_data_dir);

        // Opening either database triggers the split migration.
        let _ = open_chats_db(&app_data_dir).unwrap();

        // chats.db now holds the conversation data, byte-for-byte preserved.
        let chats_conn = Connection::open(chats_db_path(&app_data_dir)).unwrap();
        let conv_title: String = chats_conn
            .query_row("SELECT title FROM conversations WHERE id = 'conv-1'", [], |r| r.get(0))
            .unwrap();
        assert_eq!(conv_title, "Hello");
        let msg_content: String = chats_conn
            .query_row("SELECT content FROM messages WHERE id = 'msg-1'", [], |r| r.get(0))
            .unwrap();
        assert_eq!(msg_content, "hi there");
        let rejected_count: i64 = chats_conn
            .query_row("SELECT COUNT(*) FROM rejected_edits", [], |r| r.get(0))
            .unwrap();
        assert_eq!(rejected_count, 1);
        assert!(!table_exists(&chats_conn, "run_configs"), "run_configs must not leak into chats.db");

        // app.db keeps run_configs but has had the chat tables stripped out.
        let app_conn = Connection::open(app_db_path(&app_data_dir)).unwrap();
