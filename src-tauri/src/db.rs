/// Creates the Chat DB's tables if they don't exist yet: conversations,
/// messages, rejected_edits. Called once on application startup, against
/// the global `app_data_dir` (never a per-project dir, never `app.db`).
///
/// `conversations` is one row per chat session, scoped to a project root.
/// `messages` holds individual turns (user / assistant / tool), organised
/// as a TREE rather than a flat list (CHAT-004: Versioned Chat Response
/// Branches). Each message optionally points at a `parent_id` — the
/// message it followed on whatever branch it was created on. A single
/// parent can have multiple children: that's what a "version" is (e.g.
/// editing a user message, or regenerating an assistant reply, both
/// insert a new sibling under the same parent rather than overwriting or
/// deleting anything). `conversations.current_leaf_id` points at the tip
/// of whichever branch is currently the "active" one being displayed —
/// the full linear transcript for that branch is reconstructed by
/// walking `parent_id` pointers from the leaf back to the root (see
/// `load_message_graph` below). Switching versions just repoints
/// `current_leaf_id`; nothing is ever deleted or mutated.
/// `rejected_edits` records proposals the user declined so the agent can
/// be reminded not to repeat them via the system-prompt memory summary.
///
/// All three tables are scoped by a `project_root` TEXT column rather than
/// living in a per-project database, since chat history / rejected edits
/// are lightweight, cross-referenced by conversation id, and benefit from
/// a single global "list all conversations" query — unlike
/// chunks/symbols/embeddings, which are large, project-local, and never
/// queried across projects.
pub fn init_chats_db(app_data_dir: &PathBuf) -> SqlResult<()> {
    crate::logging::checkpoint(&format!("db_init: begin chats.db at {}", app_data_dir.display()));

    std::fs::create_dir_all(app_data_dir)
        .map_err(|e| rusqlite::Error::InvalidPath(e.to_string().into()))?;
    crate::logging::ok("db_init: app data directory ensured");

    crate::logging::checkpoint("db_init: opening chats.db connection (WAL pragma)");
    let conn = open_chats_db(app_data_dir)?;
    crate::logging::ok("db_init: chats.db connection opened");

    crate::logging::checkpoint("db_init: chat tables (conversations, messages, rejected_edits)");
    conn.execute_batch(
        "
        CREATE TABLE IF NOT EXISTS conversations (
            id              TEXT PRIMARY KEY,
            project_root    TEXT NOT NULL,
            title           TEXT NOT NULL DEFAULT 'New Conversation',
            created_at      TEXT NOT NULL,
            updated_at      TEXT NOT NULL,
            current_leaf_id TEXT
        );

        CREATE INDEX IF NOT EXISTS idx_conversations_project
            ON conversations(project_root, updated_at DESC);

        CREATE TABLE IF NOT EXISTS messages (
            id              TEXT PRIMARY KEY,
            conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
            parent_id       TEXT REFERENCES messages(id) ON DELETE CASCADE,
            role            TEXT NOT NULL,
            content         TEXT NOT NULL,
            tool_name       TEXT,
            created_at      TEXT NOT NULL,
            metadata        TEXT
        );

        CREATE INDEX IF NOT EXISTS idx_messages_conversation
            ON messages(conversation_id, created_at);

        CREATE INDEX IF NOT EXISTS idx_messages_parent
            ON messages(parent_id);

        CREATE TABLE IF NOT EXISTS rejected_edits (
            id           INTEGER PRIMARY KEY AUTOINCREMENT,
            message_id   TEXT REFERENCES messages(id) ON DELETE SET NULL,
            project_root TEXT NOT NULL,
            file_path    TEXT NOT NULL,
            description  TEXT NOT NULL,
            created_at   TEXT NOT NULL
        );

        CREATE INDEX IF NOT EXISTS idx_rejected_edits_project
            ON rejected_edits(project_root, created_at DESC);
    ",
    )?;
    crate::logging::ok("db_init: chat tables ready");

    crate::logging::checkpoint("db_init: message graph migration (CHAT-004)");
    migrate_messages_to_graph(&conn)?;
    crate::logging::ok("db_init: message graph migration complete");

    crate::logging::checkpoint("db_init: message metadata migration (CHAT-005)");
    migrate_add_message_metadata_column(&conn)?;
    crate::logging::ok("db_init: message metadata migration complete");

    crate::logging::ok("db_init: chats.db complete");
    Ok(())
}

// ── CHAT-005 migration: full-fidelity message metadata ─────────────────────
//
// Adds a nullable `metadata` TEXT column to `messages` holding a JSON blob
// of every UI-only field that used to live only in React state and vanish
// on reload — the generated IntentPlan, per-step statuses, agent activity
// ("api call") chips, retrieval/compression stats, attached images, pending
// login/toggle cards, etc. (see ChatMessage in types/index.ts and
// extractMessageMetadata in useChat.ts). `content` keeps holding just the
// plain-text body; `metadata` is opaque JSON the Rust side never inspects.
//
// Column-existence check rather than a `PRAGMA user_version` gate (unlike
// `migrate_messages_to_graph` above) because this can run safely on every
// launch: a fresh database already has the column from `CREATE TABLE IF NOT
// EXISTS` above, so the check below is a cheap no-op there, and it doesn't
// need to coexist with the CHAT-004 version-gated backfill logic.
fn migrate_add_message_metadata_column(conn: &Connection) -> SqlResult<()> {
    let messages_has_metadata: bool = conn
        .prepare("SELECT 1 FROM pragma_table_info('messages') WHERE name = 'metadata'")?
        .exists([])?;
    if !messages_has_metadata {
        conn.execute_batch("ALTER TABLE messages ADD COLUMN metadata TEXT;")?;
    }
    Ok(())
}

// ── CHAT-004 migration: linear message history → message graph ────────────
//
// Databases created before this feature shipped have a `messages` table
// with `role`/`content`/`created_at` but no `parent_id`, and a
// `conversations` table with no `current_leaf_id`. `CREATE TABLE IF NOT
// EXISTS` above is a no-op against those existing tables, so the columns
// are added here via `ALTER TABLE` when missing, and every conversation's
// existing (flat, chronological) message history is backfilled into a
// single linear chain: each message's `parent_id` becomes the id of the
// message immediately before it (by `created_at`, then `rowid` as a
// tiebreaker) within the same conversation, and each conversation's
// `current_leaf_id` is set to its last message. This is exactly the graph
// shape a purely-linear history already represents — one branch, no forks
// — so every existing chat keeps working unchanged; the very next edit or
// regenerate on it is what actually forks it into a real tree.
//
// Guarded by `PRAGMA user_version` so it only ever runs once per database:
// after the first run every conversation's first message legitimately has
// a NULL `parent_id` forever (it's a real root), so that column alone
// can't be used to detect "not yet migrated" on later app launches.
fn migrate_messages_to_graph(conn: &Connection) -> SqlResult<()> {
    let user_version: i32 = conn.query_row("PRAGMA user_version", [], |r| r.get(0))?;
    if user_version >= 1 {
        return Ok(());
    }

    // Add the new columns if this is an older database. Fresh databases
    // already have them from the CREATE TABLE above, so these are no-ops
    // there (and ALTER TABLE ADD COLUMN on a column that already exists
    // would error, so guard explicitly).
    let messages_has_parent: bool = conn
        .prepare("SELECT 1 FROM pragma_table_info('messages') WHERE name = 'parent_id'")?
        .exists([])?;
    if !messages_has_parent {
        conn.execute_batch(
            "ALTER TABLE messages ADD COLUMN parent_id TEXT REFERENCES messages(id) ON DELETE CASCADE;",
        )?;
    }

    let conversations_has_leaf: bool = conn
        .prepare("SELECT 1 FROM pragma_table_info('conversations') WHERE name = 'current_leaf_id'")?
        .exists([])?;
    if !conversations_has_leaf {
        conn.execute_batch("ALTER TABLE conversations ADD COLUMN current_leaf_id TEXT;")?;
    }

    // Backfill: chain every conversation's messages into a single linear
    // branch in chronological order, and point each conversation's
    // current_leaf_id at its last message. Idempotent-safe by construction
    // (re-deriving the same chain twice is harmless), but the user_version
    // guard above means this only actually runs once anyway.
    {
        let mut stmt = conn.prepare(
            "SELECT id, conversation_id FROM messages ORDER BY conversation_id, created_at, rowid",
        )?;
        let rows: Vec<(String, String)> = stmt
            .query_map([], |r| Ok((r.get(0)?, r.get(1)?)))?
            .filter_map(|r| r.ok())
            .collect();

        let mut current_conversation: Option<String> = None;
        let mut previous_id: Option<String> = None;
        let mut last_message_by_conversation: std::collections::HashMap<String, String> =
            std::collections::HashMap::new();

        for (message_id, conversation_id) in &rows {
            if current_conversation.as_deref() != Some(conversation_id.as_str()) {
                previous_id = None;
                current_conversation = Some(conversation_id.clone());
            }
            conn.execute(
                "UPDATE messages SET parent_id = ?1 WHERE id = ?2",
                params![previous_id, message_id],
            )?;
            previous_id = Some(message_id.clone());
            last_message_by_conversation.insert(conversation_id.clone(), message_id.clone());
        }

        for (conversation_id, leaf_id) in last_message_by_conversation {
            conn.execute(
                "UPDATE conversations SET current_leaf_id = ?1 WHERE id = ?2",
                params![leaf_id, conversation_id],
            )?;
        }
    }

    conn.execute_batch("PRAGMA user_version = 1;")?;
    Ok(())
}

