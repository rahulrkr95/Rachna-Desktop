/// Deletes all stored chunks (and their FTS entries) for a single file.
/// Called before re-inserting to avoid duplicates on re-index.
pub fn delete_file_chunks(app_data_dir: &PathBuf, file_path: &str) -> SqlResult<usize> {
    let conn = open_project_db(app_data_dir)?;

    // 1. Collect (rowid, id) pairs to remove from FTS / embedding tables.
    //    `rowid` is needed to clean up `embeddings_vec`, which is keyed by
    //    the integer rowid of the matching `chunks` row (see
    //    `store_embedding`) rather than by the TEXT chunk id.
    let mut stmt = conn.prepare(
        "SELECT rowid, id FROM chunks WHERE file_path = ?1"
    )?;
    let rows: Vec<(i64, String)> = stmt
        .query_map(params![file_path], |row| Ok((row.get(0)?, row.get(1)?)))?
        .filter_map(|r| r.ok())
        .collect();

    // 2. Remove FTS + embedding entries explicitly. `chunk_embeddings`
    //    declares `ON DELETE CASCADE`, but this connection never turns on
    //    `PRAGMA foreign_keys`, so SQLite won't enforce that cascade —
    //    delete from every table by hand instead. This also prevents a
    //    subtle correctness bug: if a chunk's old rowid were ever reused
    //    by a later INSERT, a stale `embeddings_vec` row would silently
    //    point ANN search at the wrong chunk's text.
    for (rowid, id) in &rows {
        conn.execute("DELETE FROM chunks_fts WHERE chunk_id = ?1", params![id])?;
        conn.execute("DELETE FROM chunk_embeddings WHERE chunk_id = ?1", params![id])?;
        conn.execute("DELETE FROM embeddings_vec WHERE rowid = ?1", params![rowid])?;
    }

    // 3. Remove chunk rows
    let deleted = conn.execute(
        "DELETE FROM chunks WHERE file_path = ?1",
        params![file_path],
    )?;

    Ok(deleted)
}


