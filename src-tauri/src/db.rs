/// Returns EVERY message belonging to `conversation_id` — the whole graph,
/// every branch, not just the currently-active path — so the caller (the TS
/// layer) can reconstruct the active transcript by walking `parent_id` from
/// `conversation.current_leaf_id`, and can offer prev/next version
/// navigation using sibling nodes (messages sharing a `parent_id`). Ordered
/// chronologically so callers can assume creation order without re-sorting.
pub fn load_message_graph(
    app_data_dir: &PathBuf,
    conversation_id: &str,
) -> SqlResult<Vec<Message>> {
    let conn = open_chats_db(app_data_dir)?;
    let mut stmt = conn.prepare(
        "SELECT id, conversation_id, parent_id, role, content, tool_name, created_at, metadata
         FROM messages
         WHERE conversation_id = ?1
         ORDER BY created_at, rowid",
    )?;

    let rows = stmt
        .query_map(params![conversation_id], row_to_message)?
        .filter_map(|r| r.ok())
        .collect();

    Ok(rows)
}

