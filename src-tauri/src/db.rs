/// A single indexed code symbol (function, class, interface, type, enum,
/// React component, or exported declaration).
#[derive(Debug, Clone, Serialize)]
pub struct Symbol {
    pub id: i64,
    pub name: String,
    #[serde(rename = "type")]
    pub kind: String,
    pub file_path: String,
    pub start_line: u32,
    pub end_line: u32,
}

/// Searches symbols by name (case-insensitive substring match).
/// Used to answer queries like "Where is login implemented?" or
/// "Find AuthProvider" before falling back to chunk/FTS search.
pub fn search_symbols(
    app_data_dir: &PathBuf,
    name_query: &str,
    limit: usize,
    root_prefix: &str,
) -> SqlResult<Vec<Symbol>> {
    let conn = open_project_db(app_data_dir)?;

    // BUG: symbol names are single identifiers (e.g. "HandleLogin",
    // "AuthHandler") — never multi-word phrases. The caller passes
    // natural-language search terms (e.g. "types api endpoints server"
    // for "What are the types of API endpoints in this server?"), and
    // the old query matched that ENTIRE phrase as one substring against
    // `name`. No real identifier contains a literal space-joined phrase
    // like that, so symbol search silently returned 0 rows for virtually
    // every plain-English question — only a message that was itself a
    // single exact identifier ever matched.
    //
    // Fix: split into individual terms and OR-match each one
    // independently, ranking rows that match more terms — and exact
    // matches — higher.
    let terms: Vec<String> = name_query
        .split_whitespace()
        .map(|t| t.to_lowercase())
        .filter(|t| !t.is_empty())
        .collect();

    if terms.is_empty() {
        return Ok(vec![]);
    }

    let root_glob = scope_glob(root_prefix);

    let like_clauses: Vec<String> = (0..terms.len())
        .map(|i| format!("LOWER(name) LIKE ?{}", i + 1))
        .collect();
    let match_count_expr: Vec<String> = (0..terms.len())
        .map(|i| format!("(CASE WHEN LOWER(name) LIKE ?{} THEN 1 ELSE 0 END)", i + 1))
        .collect();

    let root_idx  = terms.len() + 1;
    let exact_idx = terms.len() + 2;
    let limit_idx = terms.len() + 3;

    let sql = format!(
        "SELECT id, name, type, file_path, start_line, end_line,
                ({match_sum}) AS match_count
         FROM symbols
         WHERE ({like_or})
           AND REPLACE(file_path, '\\', '/') LIKE ?{root_idx}
         ORDER BY
           CASE WHEN LOWER(name) = ?{exact_idx} THEN 0 ELSE 1 END,
           match_count DESC,
           LENGTH(name) ASC
         LIMIT ?{limit_idx}",
        match_sum = match_count_expr.join(" + "),
        like_or   = like_clauses.join(" OR "),
        root_idx  = root_idx,
        exact_idx = exact_idx,
        limit_idx = limit_idx,
    );

    let mut stmt = conn.prepare(&sql)?;

    let mut params_vec: Vec<Box<dyn rusqlite::ToSql>> = terms
        .iter()
        .map(|t| Box::new(format!("%{}%", t)) as Box<dyn rusqlite::ToSql>)
        .collect();
    params_vec.push(Box::new(root_glob));
    params_vec.push(Box::new(name_query.to_lowercase()));
    params_vec.push(Box::new(limit as i64));

    let params_refs: Vec<&dyn rusqlite::ToSql> =
        params_vec.iter().map(|p| p.as_ref()).collect();

    let rows = stmt.query_map(params_refs.as_slice(), |row| {
        Ok(Symbol {
            id:         row.get(0)?,
            name:       row.get(1)?,
            kind:       row.get(2)?,
            file_path:  row.get(3)?,
            start_line: row.get(4)?,
            end_line:   row.get(5)?,
        })
    })?;

    rows.collect()
}

// ── Embedding storage / hybrid semantic search ─────────────────────────────
//
// Embeddings come from a local Ollama server (`nomic-embed-text`, 768
// dims) and are stored as raw little-endian f32 BLOBs in `chunk_embeddings`
// — no native SQLite extension required. Cosine similarity is computed in
// plain Rust at query time and blended with FTS5 bm25 relevance.

/// Serializes an embedding vector to little-endian f32 bytes for BLOB storage.
fn embedding_to_le_bytes(embedding: &[f32]) -> Vec<u8> {
    let mut bytes = Vec::with_capacity(embedding.len() * 4);
    for v in embedding {
        bytes.extend_from_slice(&v.to_le_bytes());
    }
    bytes
}


/// Calls the local Ollama embeddings endpoint for `text`. Returns `None`
/// (silently — no error propagated) if Ollama is unreachable, the request
/// fails, or the response is malformed, so callers can fall back to FTS5
/// without surfacing noisy errors for what is an optional enhancement.
pub async fn embed_chunk(text: &str, ollama_url: &str, model: &str) -> Option<Vec<f32>> {
    let client = reqwest::Client::builder()
        .timeout(std::time::Duration::from_secs(15))
        .build()
        .ok()?;

    let url = format!("{}/api/embeddings", ollama_url.trim_end_matches('/'));

    let resp = client
        .post(&url)
        .json(&serde_json::json!({ "model": model, "prompt": text }))
        .send()
        .await
        .ok()?;

    if !resp.status().is_success() {
        return None;
    }

    let body: serde_json::Value = resp.json().await.ok()?;
    let arr = body.get("embedding")?.as_array()?;

    let vec: Vec<f32> = arr
        .iter()
        .filter_map(|v| v.as_f64())
        .map(|f| f as f32)
        .collect();

    if vec.is_empty() {
        None
    } else {
        Some(vec)
    }
}

/// Inserts or replaces the embedding for `chunk_id`. Re-indexing a chunk
/// overwrites its prior vector rather than leaving a stale row behind.
///
/// Writes go to two places: the raw-BLOB `chunk_embeddings` table (kept for
/// `embedding_stats` / backward compatibility) and the `embeddings_vec`
/// `vec0` ANN index that `ann_search_chunks` actually queries. `vec0`
/// virtual tables don't support `ON CONFLICT` upserts, so re-indexing does
/// an explicit delete-then-insert there instead.
pub fn store_embedding(
    app_data_dir: &PathBuf,
    chunk_id: &str,
    embedding: &[f32],
) -> SqlResult<()> {
    let conn = open_project_db(app_data_dir)?;
    let bytes = embedding_to_le_bytes(embedding);

    conn.execute(
        "INSERT INTO chunk_embeddings (chunk_id, embedding) VALUES (?1, ?2)
         ON CONFLICT(chunk_id) DO UPDATE SET embedding = excluded.embedding",
        params![chunk_id, bytes],
    )?;

    // `embeddings_vec` is keyed by the chunk's integer rowid in `chunks`
    // (see the `init` comment on why), so look that up before mirroring
    // the write. A chunk_id with no matching `chunks` row shouldn't happen
    // in practice (chunks are always saved before their embedding is
    // requested), but if it ever did we'd rather skip the ANN mirror than
    // fail the whole call — `chunk_embeddings` above already succeeded.
    let chunk_rowid: Option<i64> = conn
        .query_row(
            "SELECT rowid FROM chunks WHERE id = ?1",
            params![chunk_id],
            |row| row.get(0),
        )
        .optional()?;

    if let Some(rowid) = chunk_rowid {
        conn.execute("DELETE FROM embeddings_vec WHERE rowid = ?1", params![rowid])?;
        conn.execute(
            "INSERT INTO embeddings_vec (rowid, embedding) VALUES (?1, ?2)",
            params![rowid, bytes],
        )?;
    }

    Ok(())
}

/// Number of concurrent in-flight requests to the local Ollama embeddings
/// endpoint. Previously mirrored the TS scanner's per-file `EMBED_CONCURRENCY`
/// (repo-scanner/run.ts) at 8: Ollama still serialises on a single
/// GPU/CPU-bound model, but a deeper queue keeps it saturated between
/// requests instead of idling on each round-trip's network latency.
pub const EMBED_CONCURRENCY: usize = 8;

/// Embeds many chunks concurrently (bounded by `EMBED_CONCURRENCY`) instead
/// of one at a time. Returns `(chunk_id, embedding)` pairs only for chunks
/// that embedded successfully — chunks where Ollama was unreachable or the
/// call failed are simply omitted, same "best-effort" contract as the old
/// per-chunk sequential loop.
///
/// This is the fix for the indexing bottleneck: previously each chunk's
/// embedding call was `.await`-ed one at a time in a plain `for` loop, so a
/// repo with a few thousand chunks meant a few thousand sequential
/// round-trips to Ollama. `buffer_unordered` keeps up to
/// `EMBED_CONCURRENCY` requests in flight at once, the same pattern
/// `run.ts` already uses on the scanner side.
///
/// Takes `(chunk_id, content)` pairs rather than `&[Chunk]` so it works
/// equally for freshly-built `Chunk`s (indexing) and `ChunkSearchResult`s
/// already round-tripped through SQLite (re-embedding) without either
/// caller needing to convert to the other's type.
pub async fn embed_chunks_concurrent(
    items: &[(String, String)],
    ollama_url: &str,
    model: &str,
) -> Vec<(String, Vec<f32>)> {
    use futures_util::stream::{self, StreamExt};

    stream::iter(items.iter().cloned().map(|(id, content)| {
        let ollama_url = ollama_url.to_string();
        let model = model.to_string();
        async move {
            embed_chunk(&content, &ollama_url, &model)
                .await
                .map(|vec| (id, vec))
        }
    }))
    .buffer_unordered(EMBED_CONCURRENCY)
    .filter_map(|result| async move { result })
    .collect::<Vec<_>>()
    .await
}

/// Stores many embeddings in a single transaction on an already-open
/// connection, instead of `store_embedding`'s pattern of opening a fresh
/// connection and committing three separate (fsync'd) writes *per chunk*.
/// For a few-thousand-chunk repo this turns several-thousand implicit
/// transactions into one.
///
/// Takes `&mut Connection` (not `app_data_dir`) deliberately, so callers
/// doing a full-repo index or re-embed can open one connection for the
/// whole run and reuse it across every file, rather than paying
/// `Connection::open()` + `PRAGMA` setup cost per chunk.
pub fn store_embeddings_batch(
    conn: &mut Connection,
    embeddings: &[(String, Vec<f32>)],
) -> SqlResult<()> {
    if embeddings.is_empty() {
        return Ok(());
    }

    let tx = conn.transaction()?;

    {
        let mut upsert_raw = tx.prepare(
            "INSERT INTO chunk_embeddings (chunk_id, embedding) VALUES (?1, ?2)
             ON CONFLICT(chunk_id) DO UPDATE SET embedding = excluded.embedding",
        )?;
        let mut lookup_rowid = tx.prepare("SELECT rowid FROM chunks WHERE id = ?1")?;
        let mut delete_vec = tx.prepare("DELETE FROM embeddings_vec WHERE rowid = ?1")?;
        let mut insert_vec =
            tx.prepare("INSERT INTO embeddings_vec (rowid, embedding) VALUES (?1, ?2)")?;

        for (chunk_id, embedding) in embeddings {
            let bytes = embedding_to_le_bytes(embedding);
            upsert_raw.execute(params![chunk_id, bytes])?;

            let chunk_rowid: Option<i64> = lookup_rowid
                .query_row(params![chunk_id], |row| row.get(0))
                .optional()?;

            if let Some(rowid) = chunk_rowid {
                delete_vec.execute(params![rowid])?;
                insert_vec.execute(params![rowid, bytes])?;
            }
        }
    }

    tx.commit()?;
    Ok(())
}



/// ANN (approximate nearest neighbour) search against the `embeddings_vec`
/// `vec0` virtual table.
///
/// This is the replacement for the old "call `get_all_embeddings`, then
/// score every one of them against the query with `cosine_similarity` in a
/// Rust loop" approach — at 30 chunks × 1000 files that was 30,000
/// full-vector comparisons on *every* search. Here it's a single SQL query
/// that does the nearest-neighbour search inside SQLite and joins straight
/// back to `chunks`, so callers get the same `ChunkSearchResult` shape the
/// FTS5 path already returns.
///
/// `k = ?2` (rather than `LIMIT ?2`) is the form sqlite-vec documents as
/// working on every SQLite version it supports — a bare `ORDER BY distance
/// LIMIT n` is only recognised as a KNN query on SQLite 3.41+.
///
/// `embeddings_vec` is created with `distance_metric=cosine`, and
/// sqlite-vec's cosine *distance* is `1 - cosine_similarity`; this
/// converts it back to a similarity score before returning so the result
/// is drop-in compatible with what `cosine_similarity()` used to produce
/// (see `search_repo` in commands.rs, which blends this with FTS5 bm25).
pub fn ann_search_chunks(
    app_data_dir: &PathBuf,
    query_embedding: &[f32],
    k: usize,
    root_prefix: &str,
) -> SqlResult<Vec<(ChunkSearchResult, f32)>> {
    let conn = open_project_db(app_data_dir)?;
    let query_bytes = embedding_to_le_bytes(query_embedding);

    // Scope ANN results to the currently-open project.
    let root_glob = scope_glob(root_prefix);

    let mut stmt = conn.prepare(
        "SELECT c.id, c.file_path, c.start_line, c.end_line, c.content, c.symbol_name, v.distance
         FROM embeddings_vec v
         JOIN chunks c ON c.rowid = v.rowid
         WHERE v.embedding MATCH ?1 AND k = ?2
           AND REPLACE(c.file_path, '\\', '/') LIKE ?3
         ORDER BY v.distance",
    )?;

    let rows = stmt.query_map(params![query_bytes, k as i64, root_glob], |row| {
        let result = ChunkSearchResult {
            id:          row.get(0)?,
            file_path:   row.get(1)?,
            start_line:  row.get(2)?,
            end_line:    row.get(3)?,
            content:     row.get(4)?,
            symbol_name: row.get(5)?,
            search_mode: default_search_mode(),
        };
        let distance: f64 = row.get(6)?;
        Ok((result, (1.0 - distance) as f32))
    })?;

    rows.collect()
}

/// Number of chunks that currently have a stored embedding, plus the total
