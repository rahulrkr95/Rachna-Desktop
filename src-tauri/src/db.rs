// ── Fast incremental chunk diff ───────────────────────────────────────────
//
// Used by the `fast_reindex_files` Tauri command to avoid a full Node.js
// scanner subprocess on every file save. The three helpers below:
//   1. Load existing symbol ranges from SQLite (for symbol-aware rechunking).
//   2. Load existing chunk content hashes (for diffing).
//   3. Atomically delete stale chunks and insert only new/modified ones.

/// Stable content hash — FNV-1a 64-bit, hex-encoded.
/// Chosen for speed (no external dep) and zero-collision probability
/// for chunks of up to ~8 KB of source text.
fn fnv1a_hex(content: &str) -> String {
    const BASIS: u64 = 0xcbf2_9ce4_8422_2325;
    const PRIME: u64 = 0x0000_0100_0000_01b3;
    let hash = content.bytes().fold(BASIS, |h, b| {
        (h ^ b as u64).wrapping_mul(PRIME)
    });
    format!("{hash:016x}")
}

/// Returns existing symbol ranges for a single file from the `symbols` table,
/// ordered by `start_line` ascending.  Used by `fast_reindex_files` so the
/// pure-Rust chunker can produce symbol-aligned chunks without spawning Node.
pub fn get_file_symbol_ranges(
    app_data_dir: &PathBuf,
    file_path: &str,
) -> SqlResult<Vec<SymbolRange>> {
    let conn = open_project_db(app_data_dir)?;
    let mut stmt = conn.prepare(
        "SELECT name, start_line, end_line
         FROM symbols
         WHERE file_path = ?1
         ORDER BY start_line",
    )?;
    let rows = stmt.query_map(params![file_path], |row| {
        Ok(SymbolRange {
            name: row.get(0)?,
            start_line: row.get(1)?,
            end_line: row.get(2)?,
        })
    })?;
    rows.collect()
}

/// Returns a map of `chunk_id → content_hash` for all stored chunks of
/// `file_path`.  The hash is computed from the stored `content` column so the
/// caller can diff new chunks without a second DB round-trip.
pub fn get_file_chunk_hashes(
    app_data_dir: &PathBuf,
    file_path: &str,
) -> SqlResult<std::collections::HashMap<String, String>> {
    let conn = open_project_db(app_data_dir)?;
    let mut stmt = conn.prepare(
        "SELECT id, content FROM chunks WHERE file_path = ?1",
    )?;
    let rows = stmt.query_map(params![file_path], |row| {
        let id: String = row.get(0)?;
        let content: String = row.get(1)?;
        Ok((id, content))
    })?;

    let mut map = std::collections::HashMap::new();
    for row in rows {
        let (id, content) = row?;
        map.insert(id, fnv1a_hex(&content));
    }
    Ok(map)
}

/// Diff-update chunks for one file in a single transaction:
///   - Stale rows  (id not in `new_chunks`) → deleted.
///   - New rows    (id not in `stored_hashes`) → inserted.
///   - Modified    (id present but hash differs) → FTS entry replaced + chunk upserted.
///   - Unchanged   (same hash) → skipped entirely.
///
/// Returns `(deleted, inserted)` counts.
pub fn diff_update_chunks(
    app_data_dir: &PathBuf,
    stored_hashes: &std::collections::HashMap<String, String>,
    new_chunks: &[Chunk],
) -> SqlResult<(usize, usize)> {
    // Identify stale ids: present in DB but absent from the new chunk set.
    let new_ids: std::collections::HashSet<&str> =
        new_chunks.iter().map(|c| c.id.as_str()).collect();
    let stale_ids: Vec<&str> = stored_hashes
        .keys()
        .filter(|id| !new_ids.contains(id.as_str()))
        .map(|s| s.as_str())
        .collect();

    // Identify chunks to (re-)insert: brand-new ids or content-hash mismatch.
    let to_insert: Vec<&Chunk> = new_chunks
        .iter()
        .filter(|c| match stored_hashes.get(&c.id) {
            Some(stored_hash) => fnv1a_hex(&c.content) != *stored_hash,
            None => true,
        })
        .collect();

    if stale_ids.is_empty() && to_insert.is_empty() {
        return Ok((0, 0));
    }

    let mut conn = open_project_db(app_data_dir)?;
    let tx = conn.transaction()?;

    // ── Delete stale chunks + their FTS rows ──────────────────────────────
    let mut deleted = 0usize;
    for id in &stale_ids {
        tx.execute("DELETE FROM chunks_fts WHERE chunk_id = ?1", params![id])?;
        deleted += tx.execute("DELETE FROM chunks WHERE id = ?1", params![id])?;
    }

    // ── Upsert new/modified chunks ────────────────────────────────────────
    {
        let mut del_fts = tx.prepare(
            "DELETE FROM chunks_fts WHERE chunk_id = ?1",
        )?;
        let mut ins_chunk = tx.prepare(
            "INSERT OR REPLACE INTO chunks \
             (id, file_path, start_line, end_line, content, symbol_name) \
             VALUES (?1, ?2, ?3, ?4, ?5, ?6)",
        )?;
        let mut ins_fts = tx.prepare(
            "INSERT INTO chunks_fts (chunk_id, content) VALUES (?1, ?2)",
        )?;

        for chunk in &to_insert {
            // Remove stale FTS entry for modified chunks (new chunks have none).
            del_fts.execute(params![chunk.id])?;
            ins_chunk.execute(params![
                chunk.id,
                chunk.file_path,
                chunk.start_line,
                chunk.end_line,
                chunk.content,
                chunk.symbol_name,
            ])?;
            ins_fts.execute(params![chunk.id, chunk.content])?;
        }
    }

    tx.commit()?;
    Ok((deleted, to_insert.len()))
}

