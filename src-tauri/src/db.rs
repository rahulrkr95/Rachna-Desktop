/// Returns distinct file_path values that end with `suffix` (path-separator
/// aware: matches on `/`-normalized paths so both `\` and `/` work).
///
/// Used by `find_chunks_by_path` to resolve a partial path / filename typed
/// by the user (e.g. "App.tsx" or "services/index.html") to one or more
/// indexed absolute file paths.
pub fn find_files_by_suffix(
    app_data_dir: &PathBuf,
    suffix: &str,
    root_prefix: &str,
) -> SqlResult<Vec<String>> {
    let conn = open_project_db(app_data_dir)?;

    // Scope the initial fetch to the current project root for efficiency.
    let root_glob = scope_glob(root_prefix);

    let mut stmt = conn.prepare(
        "SELECT DISTINCT file_path FROM chunks WHERE REPLACE(file_path, '\\', '/') LIKE ?1",
    )?;
    let all: Vec<String> = stmt
        .query_map(params![root_glob], |row| row.get::<_, String>(0))?
        .filter_map(|r| r.ok())
        .collect();

    let norm_suffix = suffix.replace('\\', "/").to_lowercase();

    let matches: Vec<String> = all
        .into_iter()
        .filter(|p| {
            let norm = p.replace('\\', "/").to_lowercase();
            norm.ends_with(&norm_suffix)
                || norm
                    .rsplit('/')
                    .next()
                    .map(|name| name == norm_suffix)
                    .unwrap_or(false)
        })
        .collect();

    Ok(matches)
}

