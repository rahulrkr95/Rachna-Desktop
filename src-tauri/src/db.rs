/// Creates the Project DB's tables if they don't exist yet: chunks,
/// chunks_fts, symbols, chunk_embeddings, embeddings_vec. Called once per
/// project the first time it's scanned (see `scan_repo` in commands.rs).
pub fn init_project_db(project_dir: &PathBuf) -> SqlResult<()> {
    crate::logging::checkpoint(&format!("db_init: begin project.db at {}", project_dir.display()));

    std::fs::create_dir_all(project_dir)
        .map_err(|e| rusqlite::Error::InvalidPath(e.to_string().into()))?;
    crate::logging::ok("db_init: project directory ensured");

    crate::logging::checkpoint("db_init: opening project.db connection (WAL pragma)");
    let mut conn = open_project_db(project_dir)?;
    crate::logging::ok("db_init: project.db connection opened");

    crate::logging::checkpoint("db_init: core tables (chunks, fts5, symbols)");
    conn.execute_batch("
        -- Main chunk store
        CREATE TABLE IF NOT EXISTS chunks (
            id         TEXT PRIMARY KEY,
            file_path  TEXT NOT NULL,
            start_line INTEGER NOT NULL,
            end_line   INTEGER NOT NULL,
            content    TEXT NOT NULL,
            symbol_name TEXT
        );

        -- Fast lookup by file (used by delete_file_chunks)
        CREATE INDEX IF NOT EXISTS idx_chunks_file
            ON chunks(file_path);

        -- FTS5 virtual table for full-text search.
        -- chunk_id is a stored column so we can JOIN back to chunks.
        -- content='' means external-content FTS — we manage inserts ourselves.
        CREATE VIRTUAL TABLE IF NOT EXISTS chunks_fts
            USING fts5(
                chunk_id UNINDEXED,
                content,
                tokenize = 'porter ascii'
            );

        -- Code symbols (functions, classes, interfaces, types, enums,
        -- React components, exported declarations) extracted by the
        -- ts-morph based scanner. Used for fast 'where is X implemented'
        -- style lookups ahead of chunk/FTS search.
        CREATE TABLE IF NOT EXISTS symbols (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            name       TEXT NOT NULL,
            type       TEXT NOT NULL,
            file_path  TEXT NOT NULL,
            start_line INTEGER NOT NULL,
            end_line   INTEGER NOT NULL
        );

        CREATE INDEX IF NOT EXISTS idx_symbols_name
            ON symbols(name);

        CREATE INDEX IF NOT EXISTS idx_symbols_file
            ON symbols(file_path);
    ")?;
    crate::logging::ok("db_init: core tables created");

    // Migration: older databases were created before `chunks.symbol_name`
    // existed. `CREATE TABLE IF NOT EXISTS` above is a no-op on those, so
    // check for the column explicitly and ALTER TABLE if it's missing.
    crate::logging::checkpoint("db_init: symbol_name column migration check");
    let has_symbol_name_col: bool = {
        let mut stmt = conn.prepare("PRAGMA table_info(chunks)")?;
        let mut rows = stmt.query([])?;
        let mut found = false;
        while let Some(row) = rows.next()? {
            let col_name: String = row.get(1)?;
            if col_name == "symbol_name" {
                found = true;
                break;
            }
        }
        found
    };

    if !has_symbol_name_col {
        conn.execute_batch("ALTER TABLE chunks ADD COLUMN symbol_name TEXT;")?;
        crate::logging::ok("db_init: symbol_name column added (migrated)");
    } else {
        crate::logging::ok("db_init: symbol_name column already present");
    }

    // ── Embedding storage (Ollama + raw BLOB) ────────────────────────────
    // `chunk_embeddings` holds one row per indexed chunk: a little-endian
    // f32 vector produced by the `nomic-embed-text` Ollama model. Kept for
    // `embedding_stats` / backward compatibility — semantic *search* now
    // goes through the `embeddings_vec` ANN index created below instead of
    // scanning these rows by hand (see `ann_search_chunks`).
    crate::logging::checkpoint("db_init: chunk_embeddings table");
    conn.execute_batch(
        "
        CREATE TABLE IF NOT EXISTS chunk_embeddings (
            chunk_id  TEXT PRIMARY KEY REFERENCES chunks(id) ON DELETE CASCADE,
            embedding BLOB NOT NULL
        );
    ",
    )?;
    crate::logging::ok("db_init: chunk_embeddings table ready");

    // ── ANN vector index (sqlite-vec `vec0` virtual table) ───────────────
    // Keyed by the *integer* SQLite rowid of the matching `chunks` row
    // (every rowid table has one implicitly, even though `chunks.id`
    // itself is a TEXT primary key), so search can `JOIN` straight back to
    // `chunks` with no extra id column to maintain.
    //
    // `vec0` fixes its column width at CREATE time. On a fresh database we
    // default to `EMBED_DIMS` (768, matching nomic-embed-text); on an
    // existing database that already has embeddings from before this
    // migration, detect the real width from a stored BLOB instead, in case
    // a different embedding model was ever configured.
    let detected_dims: usize = conn
        .query_row(
            "SELECT LENGTH(embedding) FROM chunk_embeddings LIMIT 1",
            [],
            |row| row.get::<_, i64>(0),
        )
        .optional()?
        .map(|len_bytes| (len_bytes / 4) as usize)
        .filter(|&d| d > 0)
        .unwrap_or(EMBED_DIMS);

    crate::logging::checkpoint(&format!(
        "db_init: embeddings_vec vec0 table (dims={detected_dims})"
    ));
    conn.execute_batch(&format!(
        "CREATE VIRTUAL TABLE IF NOT EXISTS embeddings_vec USING vec0(
            embedding float[{detected_dims}] distance_metric=cosine
        );"
    ))?;
    crate::logging::ok(&format!(
        "db_init: embeddings_vec vec0 table ready (dims={detected_dims})"
    ));

    // One-time backfill: if `embeddings_vec` is empty but `chunk_embeddings`
    // already has rows (a database created before this migration ran),
    // copy every existing embedding across so older repos get ANN search
    // immediately rather than needing a full "Re-embed entire repo".
    let vec_row_count: i64 =
        conn.query_row("SELECT COUNT(*) FROM embeddings_vec", [], |r| r.get(0))?;

    if vec_row_count == 0 {
        let existing: Vec<(i64, Vec<u8>)> = {
            let mut stmt = conn.prepare(
                "SELECT c.rowid, ce.embedding
                 FROM chunk_embeddings ce
                 JOIN chunks c ON c.id = ce.chunk_id",
            )?;
            let rows: Vec<(i64, Vec<u8>)> = stmt
                .query_map([], |row| Ok((row.get(0)?, row.get(1)?)))?
                .filter_map(|r| r.ok())
                .collect();
            rows
        };

        if !existing.is_empty() {
            let tx = conn.transaction()?;
            {
                let mut insert_vec = tx.prepare(
                    "INSERT INTO embeddings_vec (rowid, embedding) VALUES (?1, ?2)",
                )?;
                for (rowid, bytes) in &existing {
                    // Skip rows whose width doesn't match the detected
                    // dimension (e.g. leftovers from a since-changed
                    // embedding model) instead of failing the migration.
                    if bytes.len() / 4 == detected_dims {
                        insert_vec.execute(params![rowid, bytes])?;
                    }
                }
            }
            tx.commit()?;
            println!(
                "embeddings_vec: backfilled {} existing embedding(s) into the ANN index",
                existing.len()
            );
            crate::logging::ok(&format!(
                "db_init: embeddings_vec backfill ({} row(s))",
                existing.len()
            ));
        } else {
            crate::logging::ok("db_init: embeddings_vec backfill (nothing to backfill)");
        }
    } else {
        crate::logging::ok("db_init: embeddings_vec backfill (already populated, skipped)");
    }

    crate::logging::ok("db_init: project.db complete");
    Ok(())
}

