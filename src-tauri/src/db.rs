// src-tauri/src/db.rs
//
// SQLite persistence layer for repository chunks.
//
// Responsibilities:
//   - Open / initialise the database in the Tauri app-data directory.
//   - Create the `chunks` table (keyed by a stable chunk id).
//   - Create an FTS5 virtual table (`chunks_fts`) for full-text search.
//   - Expose search_chunks helpers
//     called by the Tauri command layer.
//
// Threading: rusqlite::Connection is not Send, so we open a fresh connection
// per call.  For a local developer tool this is perfectly acceptable —
// contention is negligible and avoids the complexity of connection pooling.

use rusqlite::{params, Connection, OptionalExtension, Result as SqlResult};
use serde::Serialize;
use std::path::PathBuf;
use std::sync::Once;
use std::collections::hash_map::DefaultHasher;

// ── Path-separator-safe project scoping ─────────────────────────────────────
//
// BUG (root cause of "No repository context found" firing on every repo,
// every language, on Windows): `file_path` is stored verbatim from the
// Node.js scanner, which uses `path.join`/`path.resolve` and therefore
// emits backslash-separated paths on Windows (e.g.
// `C:\Users\rahul\proj\src\index.ts`). Every retrieval query below scoped
// results with `file_path LIKE '<root>/%'` — a glob that hardcodes a
// forward slash right after the root. On Windows the real character there
// is `\`, so the LIKE pattern never matched a single row and every query
// silently returned zero results — regardless of repo language or project.
//
// Fix: normalise backslashes to forward slashes on BOTH sides of the
// comparison at query time (`REPLACE(file_path, '\', '/')` in SQL, plus
// normalising root_prefix here), so already-indexed databases are fixed
// immediately without requiring a re-scan.
fn scope_glob(root_prefix: &str) -> String {
    let normalized = root_prefix.replace('\\', "/");
    if normalized.is_empty() {
        "%".to_string()
    } else {
        format!("{}/%", normalized.trim_end_matches('/'))
    }
}
use std::hash::{Hash, Hasher};
// ── Embeddings (Ollama + sqlite-vec ANN search) ─────────────────────────────
//
// Embeddings are generated by a local Ollama server (nomic-embed-text, 768
// dims). Each one is still written as a raw little-endian f32 BLOB into
// `chunk_embeddings` (kept for `embedding_stats` / backward compatibility),
// but is ALSO mirrored into `embeddings_vec`, a `vec0` virtual table backed
// by the `sqlite-vec` extension (https://github.com/asg017/sqlite-vec).
// `sqlite-vec` is a small, statically-linked, pure-C SQLite extension — no
// extra binary to ship, no network calls, and it builds on every platform
// Tauri targets — so semantic search is a single ANN/KNN SQL query instead
// of pulling every stored embedding into memory and cosine-scoring it by
// hand in a Rust loop (see `ann_search_chunks` below, and the comment on
// `cosine_similarity` for what this replaced).

/// Default Ollama base URL.
pub const DEFAULT_OLLAMA_URL: &str = "http://localhost:11434";
/// Default embedding model name.
pub const DEFAULT_EMBED_MODEL: &str = "nomic-embed-text";
/// Expected embedding dimensionality for nomic-embed-text. Used as the
/// `vec0` column width for brand-new databases; existing databases detect
/// their real width from a stored embedding instead (see `init`).
pub const EMBED_DIMS: usize = 768;

// ── sqlite-vec extension loading ─────────────────────────────────────────
//
// `sqlite3_auto_extension` registers the extension's C entry point
// *process-wide*: every `Connection` opened anywhere afterwards
// automatically gets the `vec0` module, with no per-connection
// `.load_extension()` call needed. Because `open()` below is called fresh
// for every database operation in this module, registration is guarded by
// `Once` so it only happens the first time any connection is opened.
static SQLITE_VEC_REGISTERED: Once = Once::new();

fn ensure_sqlite_vec_registered() {
    SQLITE_VEC_REGISTERED.call_once(|| {
        crate::logging::checkpoint("db_init: sqlite-vec extension registration");
        unsafe {
            // SAFETY: `sqlite3_vec_init` is sqlite-vec's C extension entry
            // point — it matches the `(db, *errmsg, *api_routines) -> c_int`
            // signature SQLite's auto-extension mechanism expects. This is
            // the exact pattern sqlite-vec's own Rust docs recommend for
            // rusqlite: https://alexgarcia.xyz/sqlite-vec/rust.html
            let raw_ext: unsafe extern "C" fn(
                *mut rusqlite::ffi::sqlite3,
                *mut *mut std::os::raw::c_char,
                *const rusqlite::ffi::sqlite3_api_routines,
            ) -> std::os::raw::c_int =
                std::mem::transmute(sqlite_vec::sqlite3_vec_init as *const () as usize);

            match rusqlite::auto_extension::register_auto_extension(raw_ext) {
                Ok(()) => {
                    crate::logging::ok("db_init: sqlite-vec extension registered");
                }
                Err(e) => {
                    // Not fatal — worst case, `embeddings_vec` queries below
                    // fail and the caller (search_repo) falls back to FTS5
                    // only, the same as if Ollama itself were unreachable.
                    crate::logging::fail("db_init: sqlite-vec extension registration", &e);
                    eprintln!("sqlite-vec: failed to register extension: {e}");
                }
            }
        }
    });
}

// ── Public data types ─────────────────────────────────────────────────────

/// A single code chunk stored in (and retrieved from) SQLite.
#[derive(Debug, Clone, Serialize)]
pub struct Chunk {
    /// Stable id: "<relative_path>:<start_line>:<end_line>"
    pub id: String,
    /// Absolute file path
    pub file_path: String,
    pub start_line: u32,
    pub end_line: u32,
    pub content: String,
    /// Name of the symbol (function/class/etc.) this chunk corresponds to,
    /// if it was produced by symbol-aware chunking. `None` for gap chunks
    /// (imports/blank-line regions) and for files with no symbols at all
    /// (fallback to the old line-window chunker).
    pub symbol_name: Option<String>,
}

/// Slim result type returned by search_chunks — only the fields the UI needs.
#[derive(Debug, Clone, Serialize)]
pub struct ChunkSearchResult {
    pub id: String,
    pub file_path: String,
    pub start_line: u32,
    pub end_line: u32,
    /// A short excerpt — the raw chunk content (callers may truncate further).
    pub content: String,
    /// Symbol name this chunk corresponds to, if any (see [`Chunk::symbol_name`]).
    pub symbol_name: Option<String>,
    /// "hybrid" when semantic (embedding) re-ranking contributed to this
    /// result set, "fts5_only" when only full-text search was used (e.g.
    /// Ollama was unreachable). Denormalized onto every row so the TS layer
    /// can surface it without a separate response wrapper.
    #[serde(rename = "searchMode", default = "default_search_mode")]
    pub search_mode: String,
}

fn default_search_mode() -> String {
    "fts5_only".to_string()
}

// ── Database paths ────────────────────────────────────────────────────────
//
// THREE distinct SQLite databases now exist (previously a single
// `chunks.db` held everything, then a single `app.db` held every
// non-project table — see `LEGACY_DB_FILENAME` below and the migration
// helpers just after these path functions):
//
//   1. `app.db`     — one per install, lives directly in `app_data_dir`.
//                     Holds small global/non-chat, non-project application
//                     state only: `settings` (key/value app preferences),
//                     `project_registry` (known/recently-opened projects),
//                     and `run_configs` (saved build/run commands per
//                     project — project *metadata*, not chat data).
//   2. `chats.db`   — one per install, lives directly in `app_data_dir`,
//                     alongside `app.db`. Holds ALL chat-specific data:
//                     conversations, messages (the message graph / branches
//                     — see CHAT-004 below), and rejected_edits.
//   3. `project.db` — one per indexed project, lives at
//                     `{app_data_dir}/projects/{hash}/project.db`. Holds
//                     project-scoped indexing data only: chunks, chunks_fts,
//                     symbols, chunk_embeddings, embeddings_vec.
//
// The three never share a connection and never share a schema, so:
//   - indexing/search for one project can only ever touch that project's
//     own file, never another project's and never `chats.db`;
//   - chat operations (`open_chats_db` and everything built on it) never
//     open a `project.db` unless a caller explicitly also asks for project
//     context/search (a separate call through `open_project_db`);
//   - app-level state (settings/registry/run-configs) lives independently
//     of both chat history and any project's index.

/// Filename of the global App DB, inside `app_data_dir`. Holds settings,
/// session/app metadata, the project registry, and run_configs.
pub const APP_DB_FILENAME: &str = "app.db";
/// Filename of the global Chat DB, inside `app_data_dir`. Holds
/// conversations, messages, and rejected_edits.
pub const CHATS_DB_FILENAME: &str = "chats.db";
/// Filename of the current per-project database, inside a project's data dir.
pub const PROJECT_DB_FILENAME: &str = "project.db";
/// Filename of the single pre-split database this app used to write
/// everything into. Never written to by current code — kept only so the
/// migration helpers below can find and read from it.
const LEGACY_DB_FILENAME: &str = "chunks.db";

/// Absolute path to the global App DB (`{app_data_dir}/app.db`).
pub fn app_db_path(app_data_dir: &PathBuf) -> PathBuf {
    app_data_dir.join(APP_DB_FILENAME)
}

/// Absolute path to the global Chat DB (`{app_data_dir}/chats.db`).
pub fn chats_db_path(app_data_dir: &PathBuf) -> PathBuf {
    app_data_dir.join(CHATS_DB_FILENAME)
}

/// Absolute path to a project's Project DB
/// (`{project_dir}/project.db`, where `project_dir` = `project_data_dir(...)`).
pub fn project_db_path(project_dir: &PathBuf) -> PathBuf {
    project_dir.join(PROJECT_DB_FILENAME)
}

/// Absolute path to the legacy single-file database that may exist in
/// either an app-data dir or a per-project dir, left over from before this
/// split. Private — only the migration helpers below should ever touch it.
fn legacy_db_path(dir: &PathBuf) -> PathBuf {
    dir.join(LEGACY_DB_FILENAME)
}

/// Returns a per-project data directory: `{app_data_dir}/projects/{hash}`.
///
/// Every project gets its own `project.db` (chunks, symbols, embeddings —
/// see `init_project_db()`), so scanning/searching one project never
/// touches, grows, or slows down another project's index. The hash is
/// derived from the canonicalized project root so the same folder always
/// maps to the same directory across app restarts.
pub fn project_data_dir(app_data_dir: &PathBuf, project_root: &str) -> PathBuf {
    let normalized = project_root.replace('\\', "/");
    #[cfg(target_os = "windows")]
    let normalized = normalized.to_lowercase(); // Windows paths are case-insensitive
    let mut hasher = DefaultHasher::new();
    normalized.hash(&mut hasher);
    let slug = format!("{:016x}", hasher.finish());
    app_data_dir.join("projects").join(slug)
}

// ── Legacy → split-DB migration ──────────────────────────────────────────
//
// Before this refactor, every data directory the app touched — both the
// single global one and each per-project one — got the *same* `init()`
// called on it, which created every table (chunks/symbols/embeddings AND
// conversations/messages/rejected_edits/run_configs) in a single
// `chunks.db`, regardless of which kind of directory it actually was. In
// practice the app only ever read/wrote conversations through the global
// directory and only ever read/wrote chunks through per-project
// directories, but the *schema* was duplicated everywhere and every
// `chunks.db` carried a set of unused tables.
//
// Migration runs lazily, the first time each new-style DB
// (`app.db` / `project.db`) is opened via `open_app_db` / `open_project_db`:
//
//   1. If the new file already exists, do nothing — already migrated, or a
//      fresh install that never had a legacy `chunks.db` to begin with.
//   2. Otherwise, if a legacy `chunks.db` exists alongside it, copy it
//      byte-for-byte to the new filename first. A raw file copy (rather
//      than `ATTACH` + `INSERT..SELECT`) is what safely carries over the
//      FTS5 (`chunks_fts`) and sqlite-vec (`embeddings_vec`) virtual
//      tables' shadow tables intact, which a row-by-row copy across an
//      attached database cannot reliably guarantee.
//   3. The copy still has the *other* database's tables mixed in (an
//      app.db copy carries chunks/symbols/embeddings; a project.db copy
//      carries conversations/messages/rejected_edits/run_configs). Any
//      rows found in those foreign tables are defensively merged into the
//      correct destination database first, then the empty foreign tables
//      are dropped — so nothing is silently discarded even in an
//      unexpected/old data layout, and the resulting schema matches
//      `init_app_db` / `init_project_db` exactly (no duplication).
//   4. The legacy `chunks.db` file itself is NEVER deleted or modified —
//      it's left on disk untouched as an automatic backup. Nothing in this
//      codebase reads from it again once migration has produced a new-style
//      file next to it.

fn table_exists(conn: &Connection, table: &str) -> bool {
    conn.query_row(
        "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?1",
        params![table],
        |_| Ok(()),
    )
    .optional()
    .unwrap_or(None)
    .is_some()
}

fn table_has_rows(conn: &Connection, table: &str) -> bool {
    conn.query_row(&format!("SELECT EXISTS(SELECT 1 FROM \"{table}\")"), [], |r| {
        r.get::<_, bool>(0)
    })
    .unwrap_or(false)
}

/// Drops each named table if it exists AND is empty. Non-empty "foreign"
/// tables are left in place (and logged) rather than risk losing data —
/// callers merge any such rows into the correct DB *before* calling this.
fn drop_foreign_tables_if_empty(conn: &Connection, tables: &[&str]) {
    for &table in tables {
        if !table_exists(conn, table) {
            continue;
        }
        if table_has_rows(conn, table) {
            crate::logging::checkpoint(&format!(
                "db_migrate: leaving non-empty foreign table '{table}' in place (not dropped)"
            ));
            continue;
        }
        let _ = conn.execute_batch(&format!("DROP TABLE IF EXISTS \"{table}\";"));
    }
}

/// Best-effort: if a legacy per-project `chunks.db` copy has rows in the
/// app-scoped tables (conversations/messages/rejected_edits/run_configs —
/// never expected in normal operation, but possible from an old/unknown
/// build), copies those rows into the real `app.db` before the empty-table
/// cleanup runs. Failures here are non-fatal — the source rows are left
/// untouched in the legacy file either way.
/// Merges any app-level rows found inside a legacy per-project db into the
/// correct current-generation database: chat tables (conversations/
/// messages/rejected_edits) go to `chats.db`, `run_configs` goes to
/// `app.db`. Named `..._into_app_db` for historical continuity with the
/// original (pre-app/chats-split) migration that only ever had one
/// destination; it now fans out to both.
fn merge_foreign_app_rows_into_app_db(project_conn: &Connection, app_data_dir: &PathBuf) {
    let chat_tables = ["conversations", "messages", "rejected_edits"];
    let all_tables = ["conversations", "messages", "rejected_edits", "run_configs"];
    let any_rows = all_tables
        .iter()
        .any(|t| table_exists(project_conn, t) && table_has_rows(project_conn, t));
    if !any_rows {
        return;
    }

    crate::logging::checkpoint(
        "db_migrate: found app-level rows inside a legacy per-project db — merging into app.db / chats.db",
    );

    // Make sure both destination databases exist with the current schema
    // before merging in (this also runs the app.db -> app.db + chats.db
    // split first, in case app_data_dir still has a pre-split app.db).
    if migrate_legacy_app_db(app_data_dir).is_err() {
        return;
    }
    if migrate_app_chats_split(app_data_dir).is_err() {
        return;
    }
    if init_app_db(app_data_dir).is_err() {
        return;
    }
    if init_chats_db(app_data_dir).is_err() {
        return;
    }

    // ── run_configs -> app.db ─────────────────────────────────────────
    if table_exists(project_conn, "run_configs") {
        let app_path = app_db_path(app_data_dir);
        let attach_sql = format!(
            "ATTACH DATABASE '{}' AS app_target;",
            app_path.display().to_string().replace('\'', "''")
        );
        if project_conn.execute_batch(&attach_sql).is_ok() {
            let _ = project_conn.execute_batch(
                "INSERT OR IGNORE INTO app_target.run_configs SELECT * FROM main.run_configs;",
            );
            let _ = project_conn.execute_batch("DETACH DATABASE app_target;");
        }
    }

    // ── conversations/messages/rejected_edits -> chats.db ────────────────
    let chats_path = chats_db_path(app_data_dir);
    let attach_sql = format!(
        "ATTACH DATABASE '{}' AS chats_target;",
        chats_path.display().to_string().replace('\'', "''")
    );
    if project_conn.execute_batch(&attach_sql).is_ok() {
        for table in chat_tables {
            if table_exists(project_conn, table) {
                let _ = project_conn.execute_batch(&format!(
                    "INSERT OR IGNORE INTO chats_target.{table} SELECT * FROM main.{table};"
                ));
            }
        }
        let _ = project_conn.execute_batch("DETACH DATABASE chats_target;");
    }

    crate::logging::ok("db_migrate: merge of foreign app-level rows complete");
}

/// Same idea, mirrored: if a legacy *global* `chunks.db` copy has rows in
/// the project-scoped tables (chunks/symbols/chunk_embeddings), there's no
/// way to know which project they belonged to (the old global db wasn't
/// project-scoped), so they can't be routed to a specific `project.db`.
/// Rather than discard them, they're simply left in place — see
/// `drop_foreign_tables_if_empty`, which will skip (not drop) any non-empty
/// table. Re-scanning the affected project rebuilds its index from scratch
/// regardless, so this only matters for the rare case of wanting to inspect
/// old orphaned data by hand.
fn migrate_legacy_app_db(app_data_dir: &PathBuf) -> SqlResult<()> {
    let new_path = app_db_path(app_data_dir);
    if new_path.exists() {
        return Ok(());
    }
    let legacy_path = legacy_db_path(app_data_dir);
    if !legacy_path.exists() {
        return Ok(());
    }

    crate::logging::checkpoint(&format!(
        "db_migrate: legacy {} found — migrating app-level tables to {}",
        legacy_path.display(),
        new_path.display()
    ));

    std::fs::create_dir_all(app_data_dir)
        .map_err(|e| rusqlite::Error::InvalidPath(e.to_string().into()))?;

    std::fs::copy(&legacy_path, &new_path).map_err(|e| {
        rusqlite::Error::InvalidPath(format!("failed to copy legacy db: {e}").into())
    })?;

    if let Ok(conn) = Connection::open(&new_path) {
        drop_foreign_tables_if_empty(
            &conn,
            &["chunks", "chunks_fts", "symbols", "chunk_embeddings", "embeddings_vec"],
        );
    }

    crate::logging::ok(&format!(
        "db_migrate: app.db ready (legacy {} left in place, untouched)",
        legacy_path.display()
    ));
    Ok(())
}

fn migrate_legacy_project_db(project_dir: &PathBuf) -> SqlResult<()> {
    let new_path = project_db_path(project_dir);
    if new_path.exists() {
        return Ok(());
    }
    let legacy_path = legacy_db_path(project_dir);
    if !legacy_path.exists() {
        return Ok(());
    }

    crate::logging::checkpoint(&format!(
        "db_migrate: legacy {} found — migrating project-level tables to {}",
        legacy_path.display(),
        new_path.display()
    ));

    std::fs::create_dir_all(project_dir)
        .map_err(|e| rusqlite::Error::InvalidPath(e.to_string().into()))?;

    std::fs::copy(&legacy_path, &new_path).map_err(|e| {
        rusqlite::Error::InvalidPath(format!("failed to copy legacy db: {e}").into())
    })?;

    if let Ok(conn) = Connection::open(&new_path) {
        // `project_dir` is `{app_data_dir}/projects/{hash}` — walk back up
        // two levels to find the app_data_dir any stray app-level rows
        // belong in.
        if let Some(app_data_dir) = project_dir.parent().and_then(|p| p.parent()) {
            merge_foreign_app_rows_into_app_db(&conn, &app_data_dir.to_path_buf());
        }
        drop_foreign_tables_if_empty(
            &conn,
            &["conversations", "messages", "rejected_edits", "run_configs"],
        );
    }

    crate::logging::ok(&format!(
        "db_migrate: project.db ready (legacy {} left in place, untouched)",
        legacy_path.display()
    ));
    Ok(())
}

// ── App/Chat split migration ─────────────────────────────────────────────
//
// Before *this* refactor, `app.db` (created by `migrate_legacy_app_db`
// above) held conversations/messages/rejected_edits/run_configs all
// together. This migration splits that single file into:
//   - `chats.db`: conversations, messages, rejected_edits (chat-specific).
//   - `app.db` (rewritten in place): run_configs, plus the new `settings`
//     and `project_registry` tables created by `init_app_db`.
//
// Runs lazily, guarded so it's safe to call from both `open_app_db` and
// `open_chats_db` on every startup:
//
//   1. If `app.db` doesn't exist yet (fresh install, or a build that never
//      had the old combined schema), there's nothing to split — no-op.
//   2. If `app.db` exists but has no `conversations` table, it's already a
//      post-split, app-only database — no-op.
//   3. Otherwise, copy the chat tables out of `app.db` into `chats.db`
//      (via a temp file + atomic rename, so a crash mid-copy never leaves
//      a half-written `chats.db` that later looks "already migrated"), and
//      only once that succeeds, drop the chat tables from `app.db` in a
//      transaction. `app.db` itself is never deleted or replaced — only
//      the chat tables inside it are removed once their data is safely
//      duplicated in `chats.db`.
//   4. If a previous run got as far as producing `chats.db` but crashed
//      before step 3 finished, `chats.db` already exists AND `app.db`
//      still has `conversations` — that combination is detected below and
//      any chat rows still sitting in `app.db` are merged (INSERT OR
//      IGNORE, so nothing is duplicated) into the existing `chats.db`
//      before the chat tables are dropped from `app.db`, so no data is
//      ever lost regardless of which step a previous run was interrupted
//      at.

/// Returns true if `conn` still has the old combined schema (i.e. `app.db`
/// has not yet been split into `app.db` + `chats.db`).
fn app_db_has_unsplit_chat_tables(conn: &Connection) -> bool {
    table_exists(conn, "conversations")
}

fn migrate_app_chats_split(app_data_dir: &PathBuf) -> SqlResult<()> {
    let old_app_path = app_db_path(app_data_dir);
    if !old_app_path.exists() {
        // Fresh install — nothing to split.
        return Ok(());
    }

    let needs_split = {
        let conn = Connection::open(&old_app_path)?;
        app_db_has_unsplit_chat_tables(&conn)
    };
    if !needs_split {
        // Already split (or a fresh app-only app.db) — no-op.
        return Ok(());
    }

    crate::logging::checkpoint(
        "db_migrate: splitting legacy app.db into app.db (settings/registry/run_configs) + chats.db (conversations/messages/rejected_edits)",
    );

    let chats_path = chats_db_path(app_data_dir);
    let chat_tables = ["conversations", "messages", "rejected_edits"];

    if !chats_path.exists() {
        // ── Step A: duplicate app.db -> chats.db via temp file + atomic
        // rename, so a crash here never produces a half-written chats.db
        // that a later run mistakes for "already migrated". A raw file
        // copy safely carries over every row (including the CHAT-004
        // message-graph columns) without an ATTACH/INSERT dance.
        let tmp_path = app_data_dir.join(format!("{CHATS_DB_FILENAME}.migrating"));
        let _ = std::fs::remove_file(&tmp_path); // clear any stale partial attempt
        std::fs::copy(&old_app_path, &tmp_path).map_err(|e| {
            rusqlite::Error::InvalidPath(format!("failed to copy app.db -> chats.db: {e}").into())
        })?;

        // Strip non-chat tables (run_configs, and anything else that isn't
        // chat data) out of the copy before it becomes the real chats.db.
        {
            let mut conn = Connection::open(&tmp_path)?;
            let tx = conn.transaction()?;
            tx.execute_batch("DROP TABLE IF EXISTS run_configs;")?;
            tx.commit()?;
        }

        std::fs::rename(&tmp_path, &chats_path).map_err(|e| {
            rusqlite::Error::InvalidPath(format!("failed to finalize chats.db: {e}").into())
        })?;

        crate::logging::ok("db_migrate: chats.db created from legacy app.db (chat tables duplicated)");
    } else {
        // A previous run already produced chats.db but crashed before
        // dropping the chat tables from app.db. Defensively merge any chat
        // rows still in app.db into the existing chats.db (INSERT OR
        // IGNORE — rows already copied are simply skipped) before
        // continuing to step B.
        crate::logging::checkpoint(
            "db_migrate: chats.db already exists from a prior interrupted split — merging any remaining rows before cleanup",
        );
        let app_conn = Connection::open(&old_app_path)?;
        let attach_sql = format!(
            "ATTACH DATABASE '{}' AS chats_target;",
            chats_path.display().to_string().replace('\'', "''")
        );
        app_conn.execute_batch(&attach_sql).ok();
        for table in chat_tables {
            if table_exists(&app_conn, table) {
                let _ = app_conn.execute_batch(&format!(
                    "INSERT OR IGNORE INTO chats_target.{table} SELECT * FROM main.{table};"
                ));
            }
        }
        app_conn.execute_batch("DETACH DATABASE chats_target;").ok();
    }

    // ── Step B: now that chat data is safely duplicated in chats.db,
    // remove the chat tables from app.db in a single transaction. app.db
    // keeps run_configs (and gains settings/project_registry once
    // `init_app_db` runs next). If this step is interrupted, the branch
    // above (chats_path.exists()) makes the next attempt idempotent.
    {
        let mut conn = Connection::open(&old_app_path)?;
        let tx = conn.transaction()?;
        for table in chat_tables {
            tx.execute_batch(&format!("DROP TABLE IF EXISTS \"{table}\";"))?;
        }
        tx.commit()?;
    }
    // Reclaim the space freed by dropping the (potentially large) chat
    // tables. Best-effort: VACUUM failing is not a correctness problem.
    if let Ok(conn) = Connection::open(&old_app_path) {
        let _ = conn.execute_batch("VACUUM;");
    }

    crate::logging::ok(
        "db_migrate: app.db / chats.db split complete (chat tables removed from app.db, preserved in chats.db)",
    );
    Ok(())
}

// ── Connection helpers ────────────────────────────────────────────────────

/// Opens `dir/file_name` and enables WAL mode for better concurrent read
/// performance. Shared low-level opener behind both `open_app_db` and
/// `open_project_db` — callers should use those instead of this directly.
fn open_at(dir: &PathBuf, file_name: &str) -> SqlResult<Connection> {
    ensure_sqlite_vec_registered();
    // Defensive: a directory won't exist yet the very first time a command
    // touches it (normally `init_app_db` / `init_project_db` create it
    // first, but this keeps `open_at` safe to call standalone too).
    let _ = std::fs::create_dir_all(dir);
    let conn = Connection::open(dir.join(file_name))?;
    // WAL mode: readers don't block writers and vice-versa.
    // synchronous=NORMAL: in WAL mode this is safe (durable across app
    // crashes; only a rare OS-level power-loss could lose the last few
    // commits, which are recoverable from the WAL) and avoids an fsync on
    // every single small write — full=default fsyncs on every commit, which
    // is what made per-chunk embedding writes so slow (see store_embedding /
    // store_embeddings_batch below).
    conn.execute_batch("PRAGMA journal_mode=WAL; PRAGMA synchronous=NORMAL;")?;
    Ok(conn)
}

/// Opens the global App DB (`{app_data_dir}/app.db`) — settings,
/// session/app metadata, the project registry, and run_configs. Runs the
/// legacy-migration checks first (cheap no-ops once `app.db` is on the
/// current split-DB schema): first the pre-existing `chunks.db` -> `app.db`
/// migration, then the `app.db` -> `app.db` + `chats.db` split.
///
/// Every app-scoped function in this module (settings, project registry,
/// run_configs) is called with an `app_data_dir` obtained straight from
/// `local_data_dir()` — never from `project_data_dir()` — and opens the
/// database through this function, so app-level state is never written
/// into a project's `project.db` and never into `chats.db`.
pub fn open_app_db(app_data_dir: &PathBuf) -> SqlResult<Connection> {
    migrate_legacy_app_db(app_data_dir)?;
    migrate_app_chats_split(app_data_dir)?;
    open_at(app_data_dir, APP_DB_FILENAME)
}

